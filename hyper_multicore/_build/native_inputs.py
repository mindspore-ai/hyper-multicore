"""Content identities for consumed native tools and bounded CANN development roots."""

import os
from pathlib import Path
import platform
import re
import shlex
import shutil
import subprocess
from collections.abc import Callable

from .build_utils import timed

LIBRARIES = ("runtime", "ascendcl", "tiling_api", "platform", "c_sec", "nnopbase", "opapi_math", "opapi_nn", "ops_base")


def executable_input(program, env, digest):
    found = shutil.which(program, path=env.get("PATH"))
    if not found:
        raise ValueError(f"Missing selected preflight tool: {program}")
    path = Path(found).resolve()
    return {"path": str(path), "sha256": digest(path)}


def generator_input(env):
    """Linux CMake defaults to Unix Makefiles; explicitly preserve the chosen backend."""
    name = env.get("CMAKE_GENERATOR") or "Unix Makefiles"
    if name == "Unix Makefiles":
        backend = shutil.which("gmake", path=env.get("PATH")) or shutil.which("make", path=env.get("PATH"))
    elif name.startswith("Ninja"):
        backend = shutil.which("ninja", path=env.get("PATH"))
    else:
        backend = None
    return name, backend


def compiler_programs(compiler, env, run):
    """Ask the driver about its actual helper programs rather than unrelated PATH tools."""
    flags = shlex.split(env.get("CXXFLAGS", ""))
    linker = next(("ld." + flag.split("=", 1)[1] for flag in flags if flag.startswith("-fuse-ld=")), "ld")
    programs = {}
    for name in ("as", linker, "cc1plus", "collect2"):
        command = [*compiler["command"], *flags, f"-print-prog-name={name}"]
        if run is None:
            value = subprocess.check_output(command, env=env, text=True).strip()
        else:
            value = run(command, label=f"preflight-tool-{name}", env=env, capture=True).strip()
        found = shutil.which(value, path=env.get("PATH"))
        if found:
            programs[name] = found
    return programs


def tool_inputs(compiler, env, digest, run=None):
    """Only actual tool selection enters the key; ambient PATH remains diagnostic data."""
    generator, backend = generator_input(env)
    programs = {"compiler": compiler["command"][0], "cmake": "cmake"}
    if backend:
        programs["backend"] = backend
    programs.update(compiler_programs(compiler, env, run))
    result = {
        "selected": compiler,
        "generator": {
            "name": generator,
            **{k: env.get(k) for k in ("CMAKE_GENERATOR_PLATFORM", "CMAKE_GENERATOR_TOOLSET", "CMAKE_TOOLCHAIN_FILE")},
        },
        "programs": {name: executable_input(program, env, digest) for name, program in programs.items()},
        "compiler_environment": {k: env.get(k) for k in ("COMPILER_PATH", "GCC_EXEC_PREFIX")},
        "reusable": backend is not None,
    }
    toolchain = env.get("CMAKE_TOOLCHAIN_FILE")
    if toolchain:
        result["toolchain_file"] = digest(Path(toolchain))
    return result


def compiler_identity(value: str, run: Callable[..., str], label: str) -> dict:
    """Record an explicitly selected compiler without changing the caller environment."""
    command = shlex.split(value)
    if not command or shutil.which(command[0]) is None:
        raise ValueError(f"Missing selected C++ compiler: {command}")
    command[0] = str(Path(shutil.which(command[0])).resolve())
    return {"command": command, "version": run([*command, "--version"], label=label, capture=True)}


def tree_members(root):
    """Follow SDK directory links, while preventing cycles and excluding generated bytecode."""
    files, visited = [], set()
    for directory, children, names in os.walk(root, followlinks=True):
        resolved = Path(directory).resolve()
        if resolved in visited:
            children[:] = []
            continue
        visited.add(resolved)
        children[:] = sorted(n for n in children if n not in ("__pycache__", ".git", "docs", "examples", "tests"))
        files.extend(
            Path(directory) / n
            for n in sorted(names)
            if not n.endswith((".pyc", ".pyo")) and (Path(directory) / n).is_file()
        )
    return files


def input_paths(value):
    """Read absolute file names from the full authentication input record."""
    if isinstance(value, dict):
        return set().union(*(input_paths(k) | input_paths(v) for k, v in value.items())) if value else set()
    if isinstance(value, (list, tuple)):
        return set().union(*(input_paths(v) for v in value)) if value else set()
    return {value} if isinstance(value, str) and value.startswith("/") else set()


class NativeInputs:
    """Freeze content once per build, then detect changes before accepting a native task."""

    def __init__(self, hashes):
        self.hashes, self.trees, self.roots = hashes, {}, {}
        self.runtime_cache = {}
        self.tree_records = {}
        self.metrics = {}

    def file(self, path):
        if not path:
            raise ValueError("Missing selected native input executable")
        path = Path(path)
        return {"path": str(path.resolve(strict=True)), "sha256": self.hashes(path)}

    def tree(self, path):
        path = Path(path)
        if path in self.tree_records:
            return self.tree_records[path]
        # Reuse enumeration of an enclosing root within this collection pass.
        parent = next((root for root in self.trees if path.is_relative_to(root)), None)
        members = (
            [Path(p) for p in self.trees[parent] if Path(p).is_relative_to(path)]
            if parent is not None
            else tree_members(path)
        )
        self.trees[path] = set(map(str, members))
        self.roots[path] = str(path.resolve())
        record = {str(p): self.file(p) for p in members if p.is_file()}
        self.tree_records[path] = record
        return record

    def scope(self, inputs):
        """Freeze the subset consumed by a single task, including its directory memberships."""
        names = input_paths(inputs)
        paths = {p for p in self.hashes.files if str(p) in names}
        roots = {root for root, members in self.trees.items() if names.intersection(members)}
        return lambda: self.validate(paths, roots)

    def validate(self, paths=None, roots=None):
        with timed(self.metrics, "native-file-validation"):
            for path in self.hashes.files if paths is None else paths:
                self.hashes(path)
        with timed(self.metrics, "native-directory-validation"):
            self.validate_roots(self.trees if roots is None else roots)

    def validate_roots(self, roots):
        for root in roots:
            if str(root.resolve()) != self.roots[root]:
                raise RuntimeError(f"Native development inputs changed during build: {root}")
        # An enclosing inventory detects additions/removals in registered subtrees too.
        selected = [
            root for root in roots if not any(root != parent and root.is_relative_to(parent) for parent in roots)
        ]
        for root in selected:
            if set(map(str, tree_members(root))) != self.trees[root]:
                raise RuntimeError(f"Native development inputs changed during build: {root}")

    def compiler(self, identity, env, run):
        """Include the driver, real helpers and selected CMake backend, not just --version."""
        contract = tool_inputs(identity, env, self.hashes, run)
        for record in contract["programs"].values():
            self.file(record["path"])
        return self.enrich_tools(contract, env, run)

    def enrich_tools(self, contract, env, run):
        paths = tuple(sorted({r["path"] for r in contract["programs"].values()}))
        key = paths, env.get("LD_LIBRARY_PATH")
        if key not in self.runtime_cache:
            binaries = []
            for path in paths:
                with Path(path).open("rb") as source:
                    if source.read(4) == b"\x7fELF":
                        binaries.append(path)
            files = {}
            if binaries:
                output = run(["ldd", *binaries], label="native-tool-runtime-inputs", env=env, capture=True)
                if "not found" in output:
                    raise RuntimeError(f"Missing native compiler runtime: {output}")
                files = {p: self.file(p) for p in set(re.findall(r"(?:=>\s+)?(/[^\s:]+)\s+\(", output))}
            self.runtime_cache[key] = files
        return {**contract, "runtime_libraries": self.runtime_cache[key]}

    def common_tools(self, identities, env, run):
        result = {
            name: self.file(shutil.which(name, path=env.get("PATH")))
            for name in ("gcc", "g++", "bisheng", "cmake", "ld", "make", "asc_opc")
        }
        result["selected_cxx"] = self.compiler(identities["selected_cxx"], env, run)
        selected_c = shlex.split(env.get("CC", "cc"))
        selected_c[0] = shutil.which(selected_c[0], path=env.get("PATH"))
        c_identity = {
            "command": selected_c,
            "version": run([*selected_c, "--version"], label="native-c-version", env=env, capture=True),
        }
        c_env = {**env, "CXXFLAGS": env.get("CFLAGS", "")}
        result["selected_c"] = self.compiler(c_identity, c_env, run)
        frontend = run([*selected_c, "-print-prog-name=cc1"], label="native-c-frontend", env=env, capture=True).strip()
        resolved = shutil.which(frontend, path=env.get("PATH"))
        if resolved:
            result["c_frontend"] = self.file(resolved)
        bisheng = {"command": [result["bisheng"]["path"]], "version": identities["bisheng"]["version"]}
        result["bisheng_helpers"] = self.compiler(bisheng, env, run)
        return result

    def cann(self, cann, env, run, python_files=()):
        """Hash bounded CMake include/resource roots and declared CANN link dependencies."""
        cann = Path(cann)
        python_packages = (
            "asc_opc_tool",
            "asc_op_compile_base",
            "op_compile_tool",
            "opc_tool",
            "tbe",
            "te",
            "te_fusion",
            "msobjdump",
        )
        roots = (
            "include",
            f"{platform.machine()}-linux/pkg_inc",
            "compiler/tikcpp",
            "compiler/asc/include",
            "compiler/asc/impl",
            "compiler/asc/cmake",
            "compiler/asc/python",
            "compiler/ascendc/include",
            "compiler/ascendc/impl",
            "compiler/ascendc/cmake",
            "compiler/ascendc/python",
            "compiler/python",
            "lib64/cmake",
            "tools/bisheng_compiler/lib/clang",
            "opp/built-in/op_impl/ai_core/tbe/impl/util",
            "opp/built-in/op_impl/ai_core/tbe/impl_mode",
            "opp/built-in/op_impl/ai_core/tbe/config",
        )
        roots += tuple("python/site-packages/" + name for name in python_packages)
        files = {}
        for relative in roots:
            path = cann / relative
            if path.is_dir():
                files.update(self.tree(path))
        libraries = [cann / "lib64" / f"lib{name}.so" for name in LIBRARIES]
        libraries = [p for p in libraries if p.is_file()]
        for path in libraries:
            files[str(path)] = self.file(path)
        if libraries:
            output = run(["ldd", *map(str, libraries)], label="cann-native-link-inputs", env=env, capture=True)
            if "not found" in output:
                raise RuntimeError(f"Missing CANN native link inputs: {output}")
            for path in set(re.findall(r"(?:=>\s+)?(/[^\s:]+)\s+\(", output)):
                files[path] = self.file(path)
        files.update(self.python_dependencies(cann, python_files))
        return files

    def python_dependencies(self, cann, modules):
        files = {}
        site = (cann / "python/site-packages").resolve()
        for name in modules:
            path = Path(name).resolve()
            if not path.is_relative_to(cann.resolve()) or not path.is_file():
                continue
            if path.is_relative_to(site):
                package = site / path.relative_to(site).parts[0]
                if package.is_dir():
                    files.update(self.tree(package))
                    continue
            files[str(path)] = self.file(path)
        return files

    def verify_consumed(self, work, cann):
        """Check compiler depfiles/CMake modules against the pre-build CANN input inventory."""
        cann = Path(cann).resolve()
        known = {p.resolve() for p in self.hashes.files}
        for depfile in Path(work).rglob("*.o.d"):
            tokens = shlex.split(depfile.read_text().replace("\\\n", " ").partition(":")[2])
            self.verify_paths((Path(p) for p in tokens if Path(p).is_absolute()), cann, known)
        for makefile in Path(work).rglob("CMakeFiles/Makefile.cmake"):
            values = re.findall(r'"([^"\n]+)"', makefile.read_text())
            self.verify_paths((Path(p) for p in values if Path(p).is_absolute()), cann, known)

    def verify_paths(self, paths, cann, known):
        for path in paths:
            real = path.resolve()
            if real.is_relative_to(cann) and path.is_file() and real not in known:
                raise RuntimeError(f"Consumed CANN input is missing from native identity: {path}")
